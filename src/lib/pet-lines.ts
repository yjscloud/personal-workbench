export type LineGroup = keyof typeof LINES;

/**
 * 填台词里的称呼。
 *
 * 只有 `{name}` 一个占位符：算账、数天数这类事不该由台词库做 ——
 * 一旦这里开始接收"还剩几天""有几件待办"，台词就很容易长成助手腔。
 */
export function fill(line: string, vars: { name?: string } = {}): string {
  return line.replace(/\{name\}/g, String(vars.name || '').trim() || '你');
}

/** 从一组台词里挑一句，尽量不跟上一句重样（只有一句时就直接用那一句） */
export function pickLine(group: LineGroup, last?: string): string {
  const pool = LINES[group] as readonly string[];
  if (pool.length <= 1) return pool[0] ?? '';
  for (let i = 0; i < 8; i += 1) {
    const line = pool[Math.floor(Math.random() * pool.length)];
    if (line !== last) return line;
  }
  return pool[0];
}
