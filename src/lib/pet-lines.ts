export type LineGroup = keyof typeof LINES;

/**
 * 填台词里的占位符。
 *
 * `{name}` 是称呼、`{days}` 是数字。数字由**调用方**算好再填进来 ——
 * 这个模块只管措辞，不算账；把"还能撑几天"的算法塞进来，
 * 改一句台词就得连带读一遍余额快照的结构。
 */
export function fill(line: string, vars: { name?: string; days?: number } = {}): string {
  return line
    .replace(/\{name\}/g, String(vars.name || '').trim() || '你')
    .replace(/\{days\}/g, vars.days === undefined ? '' : String(vars.days));
}

/** 从一组台词里挑一句，尽量不跟上一句重样（只有一句时就直接用那一句） */
export function pickLine(group: LineGroup, last?: string): string {
  const pool = LINES[group] as readonly string[];
  if (pool.length <= 1) return pool[0] ?? '';
  for (let i = 0; i < 8; i += 1) {
    const line = pool[Math.floor(Math.random() * pool.length)];
    if (line !== last) return line;
  }
  return pool[0];
}
